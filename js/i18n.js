  let currentLang = localStorage.getItem('scp_lang') || 'en';

  function get(key) {
    const keys = key.split('.');
    let obj = translations[currentLang] || translations.en;
    const en  = translations.en;
    let enObj = en;
    for (const k of keys) {
      obj   = obj   && obj[k]   !== undefined ? obj[k]   : undefined;
      enObj = enObj && enObj[k] !== undefined ? enObj[k] : undefined;
    }
    return obj || enObj || key;
  }

  function t(key, vars = {}) {
    let str = get(key);
    if (typeof str !== 'string') return key;
    Object.entries(vars).forEach(([k, v]) => {
      str = str.replace(`{{${k}}}`, v);
    });
    return str;
  }

  function setLang(lang) {
    if (!translations[lang]) return;
    currentLang = lang;
    localStorage.setItem('scp_lang', lang);
    updateDOM();
  }

  function getLang() { return currentLang; }

